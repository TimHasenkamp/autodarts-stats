<h1>Datenschutz</h1>
<div class="card">
  <p>Your Darts zeigt Statistiken von Dart-Matches, die an lokalen Autodarts-Boards gespielt wurden.</p>
  <p>Gespeichert werden:</p>
  <ul>
    <li>der am Board eingegebene Spielername (und ggf. die Autodarts-Benutzer-ID bei angemeldeten Spielern),</li>
    <li>Spielverlauf und daraus berechnete Statistiken (Average, Checkouts, 180er, Siege, Legs),</li>
    <li>Datum und Uhrzeit des Matches sowie das Board, an dem gespielt wurde.</li>
  </ul>
  <p>Wer seine Daten löschen lassen möchte, wendet sich an die Person, die dieses Board betreibt. Spieler können samt aller Statistiken vollständig entfernt werden.</p>
</div>
